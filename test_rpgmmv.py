import json
import os
import shutil
import tempfile
import unittest

from readers import rpgmmv
from readers.base import PatchError

R = rpgmmv.Reader()


def cmd(code, *params, indent=0):
    return {"code": code, "indent": indent, "parameters": list(params)}


def msg(texts, speaker=None, indent=0):
    p = ["Actor1", 0, 0, 2] + ([speaker] if speaker is not None else [])
    return [cmd(101, *p, indent=indent)] + [cmd(401, t, indent=indent) for t in texts]


def dump(path, data, kind="compact"):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if kind == "lines":
        s = "[\n" + ",\n".join(json.dumps(e, ensure_ascii=False, separators=(",", ":")) for e in data) + "\n]"
    elif kind == "indent":
        s = json.dumps(data, ensure_ascii=False, indent=2)
    else:
        s = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    with open(path, "wb") as f:
        f.write(s.encode("utf-8"))


PLUGINS = ('// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n'
           '{"name":"Menu","status":true,"description":"説明","parameters":{"title":"メニュー","key":"ok","file":"背景.png"}},\n'
           '{"name":"Ascii","status":true,"description":"x","parameters":{"a":"hello"}}\n];\n')


def build(base, mz=False):
    data = os.path.join(base, "data" if mz else os.path.join("www", "data"))
    js = os.path.join(base, "js" if mz else os.path.join("www", "js"))
    sp = "ナレ" if mz else None
    ev1 = {"id": 1, "name": "EV001", "pages": [{"list":
        msg(["こんにちは", "元気？"], sp) + [cmd(102, ["はい", "いいえ"], 1, 0, 0, 0),
                                              cmd(402, 0, "はい"), cmd(0), cmd(404)]
        + [cmd(108, "コメント"), cmd(355, "var x = 'あ'"), cmd(655, "y")]
        + msg(["さよなら"], sp) + [cmd(0)]}]}
    dump(os.path.join(data, "Map001.json"),
         {"displayName": "町", "events": [None, ev1]})
    dump(os.path.join(data, "Map002.json"),
         {"displayName": "", "events": [None, {"id": 1, "pages": [{"list":
          msg(["二つ目の", "マップ", "です", "ね"], sp) + [cmd(0)]}]}]})
    dump(os.path.join(data, "MapInfos.json"),
         [None, {"id": 1, "name": "A", "order": 2, "parentId": 0},
          {"id": 2, "name": "B", "order": 1, "parentId": 0}], "lines")
    dump(os.path.join(data, "CommonEvents.json"),
         [None, {"id": 1, "name": "ce", "list": msg(["共通"], sp) + [cmd(0)]}], "lines")
    dump(os.path.join(data, "Troops.json"),
         [None, {"id": 1, "name": "t", "pages": [{"list": msg(["戦闘"]) + [cmd(0)]}]}], "lines")
    dump(os.path.join(data, "Actors.json"),
         [None, {"id": 1, "name": "勇者", "nickname": "", "profile": "紹介", "note": "<メモ>",
                 "characterName": "Actor1"}], "lines")
    dump(os.path.join(data, "System.json"),
         {"gameTitle": "題名", "currencyUnit": "円", "terms": {"basic": ["レベル"], "messages": {"k": "文"}}})
    os.makedirs(js, exist_ok=True)
    with open(os.path.join(js, "plugins.js"), "wb") as f:
        f.write(PLUGINS.encode("utf-8"))
    return base


def jload(p):
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def read(base, rel):
    with open(os.path.join(base, *rel.split("/")), "rb") as f:
        return f.read()


class Base(unittest.TestCase):
    mz = False

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.root = build(os.path.join(self.tmp, "g"), self.mz)
        self.out = os.path.join(self.tmp, "out")
        self.pre = "data/" if self.mz else "www/data/"

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def lines(self):
        return {l.id: l for l in R.extract(self.root)}


class TestMV(Base):
    def test_detect(self):
        self.assertTrue(R.detect(self.root))
        self.assertFalse(R.detect(self.tmp))

    def test_registry_name(self):
        self.assertIs(rpgmmv.READER, rpgmmv.Reader)

    def test_order_and_kinds(self):
        ls = R.extract(self.root)
        self.assertEqual([l.order for l in ls], list(range(len(ls))))
        from project import KINDS
        self.assertTrue(all(l.kind in KINDS for l in ls))
        src = [l.source for l in ls if l.scene.startswith("Map")]
        # MapInfos order puts Map002 (order 1) before Map001 (order 2)
        self.assertEqual(src[0], "二つ目の\nマップ\nです\nね")
        self.assertIn("こんにちは\n元気？", src)
        self.assertNotIn("コメント", [l.source for l in ls])
        self.assertFalse(any("var x" in l.source for l in ls))
        self.assertFalse(any(l.source == "<メモ>" for l in ls))

    def test_ids_stable(self):
        a = [l.id for l in R.extract(self.root)]
        b = [l.id for l in R.extract(self.root)]
        self.assertEqual(a, b)
        self.assertIn(self.pre + "Map001.json#events/1/pages/0/list/0", a)

    def test_choices_and_plugins(self):
        ls = R.extract(self.root)
        self.assertEqual([l.source for l in ls if l.kind == "choice"], ["はい", "いいえ"])
        pl = [l.source for l in ls if l.kind == "plugin"]
        self.assertEqual(pl, ["メニュー"])  # not 'ok', not the .png, not the ASCII plugin

    def test_roundtrip_identity_when_unchanged(self):
        self.assertEqual(R.apply(self.root, self.out, R.extract(self.root)), [])
        self.assertFalse(os.path.exists(self.out))

    def test_apply_equal_count_and_untouched(self):
        ls = R.extract(self.root)
        t = next(l for l in ls if l.source.startswith("こんにちは"))
        t.translation = "Hello\nHow are you?"
        c = next(l for l in ls if l.source == "はい")
        c.translation = "Yes"
        w = R.apply(self.root, self.out, ls)
        self.assertEqual(w, [self.pre + "Map001.json"])
        d = json.loads(read(self.out, w[0]))
        lst = d["events"][1]["pages"][0]["list"]
        self.assertEqual([c["parameters"][0] for c in lst[1:3]], ["Hello", "How are you?"])
        self.assertEqual(lst[3]["parameters"][0], ["Yes", "いいえ"])
        # file was compact, stays compact
        self.assertNotIn(b"\n", read(self.out, w[0]))
        for rel in ("Map002.json", "System.json", "Actors.json"):
            self.assertEqual(read(self.root, self.pre + rel), read(self.root, self.pre + rel))
            self.assertFalse(os.path.exists(os.path.join(self.out, *(self.pre + rel).split("/"))))

    def test_resplit_more_and_fewer(self):
        ls = R.extract(self.root)
        a = next(l for l in ls if l.source.startswith("こんにちは"))
        a.translation = "one\ntwo\nthree\nfour"          # 2 -> 4
        b = next(l for l in ls if l.source == "さよなら")
        b.translation = "bye"
        w = R.apply(self.root, self.out, ls)
        lst = json.loads(read(self.out, w[0]))["events"][1]["pages"][0]["list"]
        self.assertEqual([c["parameters"][0] for c in lst[1:5]], ["one", "two", "three", "four"])
        self.assertTrue(all(c["code"] == 401 for c in lst[1:5]))
        self.assertEqual(lst[5]["code"], 102)
        # fewer: 4 -> 2 on Map002, with indent preserved
        m2 = next(l for l in ls if l.source.startswith("二つ目"))
        m2.translation = "A\nB"
        R.apply(self.root, self.out, ls)
        l2 = json.loads(read(self.out, self.pre + "Map002.json"))["events"][1]["pages"][0]["list"]
        self.assertEqual([c["code"] for c in l2], [101, 401, 401, 0])
        # re-extract of patched copy sees the translations in the same play order

    def test_resplit_keeps_indent(self):
        p = os.path.join(self.root, *(self.pre + "CommonEvents.json").split("/"))
        d = jload(p)
        d[1]["list"] = msg(["一", "二"], None, indent=2) + [cmd(0)]
        dump(p, d, "lines")
        ls = R.extract(self.root)
        l = next(x for x in ls if x.source == "一\n二")
        l.translation = "a\nb\nc"
        R.apply(self.root, self.out, ls)
        lst = json.loads(read(self.out, self.pre + "CommonEvents.json"))[1]["list"]
        self.assertEqual([c["indent"] for c in lst[:4]], [2, 2, 2, 2])
        # linewise style preserved
        self.assertTrue(read(self.out, self.pre + "CommonEvents.json").startswith(b"[\nnull,\n"))

    def test_plugins_roundtrip_exact(self):
        ls = R.extract(self.root)
        p = next(l for l in ls if l.kind == "plugin")
        p.translation = "Menu"
        w = R.apply(self.root, self.out, ls)
        self.assertEqual(w, ["www/js/plugins.js"])
        want = PLUGINS.replace('"メニュー"', '"Menu"').encode("utf-8")
        self.assertEqual(read(self.out, w[0]), want)

    def test_stale_locator(self):
        ls = R.extract(self.root)
        a = next(l for l in ls if l.source.startswith("こんにちは"))
        a.translation = "x"
        a.source = "改変された"
        with self.assertRaises(PatchError):
            R.apply(self.root, self.out, ls)
        p = next(l for l in ls if l.kind == "plugin")
        p.translation, p.source = "x", "違う"
        a.source, a.translation = "こんにちは\n元気？", ""
        with self.assertRaises(PatchError):
            R.apply(self.root, self.out, ls)

    def test_stale_when_group_changed(self):
        ls = R.extract(self.root)
        a = next(l for l in ls if l.source.startswith("こんにちは"))
        a.translation = "x"
        a.locator["n"] = 1
        with self.assertRaises(PatchError):
            R.apply(self.root, self.out, ls)

    def test_indented_json_preserved(self):
        p = os.path.join(self.root, *(self.pre + "Map002.json").split("/"))
        d = jload(p)
        dump(p, d, "indent")
        ls = R.extract(self.root)
        next(l for l in ls if l.source.startswith("二つ目")).translation = "A\nB\nC\nD"
        R.apply(self.root, self.out, ls)
        self.assertIn(b'\n  "events"', read(self.out, self.pre + "Map002.json"))

    def test_codes_preserved(self):
        p = os.path.join(self.root, *(self.pre + "CommonEvents.json").split("/"))
        d = jload(p)
        d[1]["list"] = msg(["\\N[1]は\\C[2]赤\\C[0]"]) + [cmd(0)]
        dump(p, d, "lines")
        ls = R.extract(self.root)
        l = next(x for x in ls if "\\N[1]" in x.source)
        self.assertEqual(l.source, "\\N[1]は\\C[2]赤\\C[0]")


class TestMZ(Base):
    mz = True

    def test_detect_and_speaker(self):
        self.assertTrue(R.detect(self.root))
        ls = R.extract(self.root)
        d = next(l for l in ls if l.source.startswith("こんにちは"))
        self.assertEqual(d.speaker, "ナレ")
        self.assertTrue(d.id.startswith("data/Map001.json#"))

    def test_plugins_path_and_357(self):
        p = os.path.join(self.root, "data", "CommonEvents.json")
        d = jload(p)
        d[1]["list"] = [cmd(357, "Menu", "show", "表示", {"text": "文字", "n": "5"}), cmd(0)]
        dump(p, d, "lines")
        ls = R.extract(self.root)
        self.assertEqual([l.source for l in ls if l.kind == "plugin" and l.file.endswith(".json")], ["文字"])
        self.assertTrue(any(l.file == "js/plugins.js" for l in ls))
        t = next(l for l in ls if l.source == "文字")
        t.translation = "text"
        R.apply(self.root, self.out, ls)
        got = json.loads(read(self.out, "data/CommonEvents.json"))[1]["list"][0]["parameters"][3]
        self.assertEqual(got, {"text": "text", "n": "5"})


if __name__ == "__main__":
    unittest.main()
